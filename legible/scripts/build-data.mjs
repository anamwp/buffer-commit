// Generates compact data modules used by the rules engine and the screen-reader
// preview. Run with `pnpm build:data`; the output is committed so builds don't
// depend on these dev-only packages.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);

// 1. Dictionary for hashtag segmentation (SCOWL levels 10-40 via wordlist-english).
const words = new Set();
for (const level of [10, 20, 35, 40]) {
  for (const w of require(`wordlist-english/english-words-${level}.json`)) {
    const lower = w.toLowerCase();
    if (/^[a-z]+$/.test(lower)) words.add(lower);
  }
}
// Social-media vocabulary that general dictionaries miss.
const extra = `ai ux ui saas b2b b2c devrel devops api apis app apps blog vlog vlogger podcast
webinar livestream instagram insta linkedin tiktok youtube facebook threads bluesky mastodon
pinterest substack startup startups founder founders indie hacker hackers fintech edtech
healthtech martech tech techie selfie selfies reels reel newsletter newsletters ecommerce
ecom shopify wordpress gutenberg nonprofit nonprofits sustainability sustainable diy ootd
throwback tbt monday tuesday wednesday thursday friday saturday sunday january february march
april june july august september october november december covid remote hybrid onboarding
cybersecurity crypto web3 nft javascript typescript python opensource github coding coder
coders dev devs data analytics seo ux ui alt wcag a11y inclusive neurodiverse adhd mentalhealth
selfcare wellness keto vegan foodie foodies travel wanderlust smb smbs ceo cto cmo hr okr okrs
`.split(/\s+/).filter(Boolean);
for (const w of extra) words.add(w);
// Drop single letters except a/i so segmentation can't shred words.
for (const w of [...words]) if (w.length === 1 && w !== "a" && w !== "i") words.delete(w);

const sorted = [...words].sort();
writeFileSync(
  "src/lib/rules/dictionary-data.ts",
  "// GENERATED by scripts/build-data.mjs - do not edit.\n" +
    "// Word list derived from SCOWL (Copyright 2000-2016 Kevin Atkinson, see THIRD_PARTY_NOTICES.md).\n" +
    `export const WORDS = ${JSON.stringify(sorted.join(" "))};\n`,
);

// 2. Emoji -> CLDR short name for the screen-reader preview.
const byEmoji = require("unicode-emoji-json/data-by-emoji.json");
const names = {};
for (const [emoji, data] of Object.entries(byEmoji)) names[emoji] = data.name;
writeFileSync(
  "src/lib/speech/emoji-names.ts",
  "// GENERATED by scripts/build-data.mjs - do not edit. Source: unicode-emoji-json (MIT).\n" +
    `export const EMOJI_NAMES: Record<string, string> = ${JSON.stringify(names)};\n`,
);

console.log(`dictionary: ${sorted.length} words; emoji names: ${Object.keys(names).length}`);
